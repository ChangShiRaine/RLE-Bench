"""Reference learned estimator for rgb-depth-model-training subtask (verifier-side).

A small CNN trained from scratch on design-seed renders. The Oracle's
train_solution.py (generated by build_assets.py) carries a copy of PoseNet,
since the agent container has no verifier harness, and trains it on the GPU
inside the agent phase.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch
from torch import nn
from torch.nn import functional as F

from . import spec, torch_contract, train_harness
from .reference_labels import label_shape


class PoseNet(nn.Module):
    """Calibrated object-centric CNN: pose channels plus T/C/F logits.

    The full frame is much larger than the block. A blind strided CNN loses
    the silhouette before its orientation head sees it. This model uses the
    public red appearance and camera calibration to center a high-resolution
    crop, then learns pose residuals and the shape-specific angle convention.
    """

    def __init__(self):
        super().__init__()
        self.crop_size = 160
        self.crop_half_pixels = 112.0
        def block(cin, cout, stride):
            return nn.Sequential(
                nn.Conv2d(cin, cout, 3, stride=stride, padding=1, bias=False),
                nn.BatchNorm2d(cout),
                nn.ReLU(inplace=True))
        self.net = nn.Sequential(
            block(6, 32, 2), block(32, 64, 2), block(64, 96, 2),
            block(96, 128, 2), block(128, 160, 2),
            nn.AdaptiveAvgPool2d(1))
        self.head = nn.Sequential(
            nn.Linear(166, 256), nn.ReLU(inplace=True),
            nn.Linear(256, 4))
        self.shape_head = nn.Linear(166, 3)
        self.fx = float(spec.intrinsics()[0, 0])
        self.fy = float(spec.intrinsics()[1, 1])
        self.cx = float(spec.intrinsics()[0, 2])
        self.cy = float(spec.intrinsics()[1, 2])
        self.register_buffer(
            "camera_rotation",
            torch.as_tensor(spec.camera_rotation(), dtype=torch.float32))
        self.register_buffer(
            "camera_position",
            torch.as_tensor(spec.CAM_POS, dtype=torch.float32))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        batch, _, height, width = x.shape
        red, green, blue = x[:, 0], x[:, 1], x[:, 2]
        mask = ((red > (60.0 / 255.0))
                & (red > 1.35 * green)
                & (red > 1.35 * blue)).to(dtype=x.dtype)

        rows = torch.arange(height, dtype=x.dtype, device=x.device)
        cols = torch.arange(width, dtype=x.dtype, device=x.device)
        mass = mask.sum(dim=(1, 2)).clamp_min(1.0)
        u = (mask.sum(dim=1) * cols.unsqueeze(0)).sum(dim=1) / mass
        v = (mask.sum(dim=2) * rows.unsqueeze(0)).sum(dim=1) / mass

        du = (cols.unsqueeze(0) - u.unsqueeze(1)) / self.crop_half_pixels
        dv = (rows.unsqueeze(0) - v.unsqueeze(1)) / self.crop_half_pixels
        col_mass = mask.sum(dim=1)
        row_mass = mask.sum(dim=2)
        var_u = (col_mass * du.square()).sum(dim=1) / mass
        var_v = (row_mass * dv.square()).sum(dim=1) / mass
        cov_uv = (
            mask * dv.unsqueeze(2) * du.unsqueeze(1)
        ).sum(dim=(1, 2)) / mass

        axis = torch.linspace(-1.0, 1.0, self.crop_size,
                              dtype=x.dtype, device=x.device)
        grid_u = (u[:, None, None]
                  + self.crop_half_pixels * axis[None, None, :])
        grid_v = (v[:, None, None]
                  + self.crop_half_pixels * axis[None, :, None])
        grid_u = grid_u.expand(batch, self.crop_size, self.crop_size)
        grid_v = grid_v.expand(batch, self.crop_size, self.crop_size)
        grid = torch.stack((2.0 * grid_u / float(width - 1) - 1.0,
                            2.0 * grid_v / float(height - 1) - 1.0), dim=-1)
        crop_input = torch.cat((x, mask.unsqueeze(1)), dim=1)
        crop = F.grid_sample(crop_input, grid, mode="bilinear",
                             padding_mode="zeros", align_corners=True)
        visual = self.net(crop).flatten(1)

        d_camera = torch.stack(((u - self.cx) / self.fx,
                                -(v - self.cy) / self.fy,
                                -torch.ones_like(u)), dim=1)
        d_world = d_camera @ self.camera_rotation.t()
        scale = ((spec.BLOCK_HEIGHT / 2.0 - self.camera_position[2])
                 / d_world[:, 2].clamp_max(-1e-6))
        center_xy = (self.camera_position[:2].unsqueeze(0)
                     + scale.unsqueeze(1) * d_world[:, :2])

        geometry = torch.stack((u / float(width) - 0.5,
                                v / float(height) - 0.5,
                                mass / float(height * width) * 50.0,
                                var_u, cov_uv, var_v), dim=1)
        features = torch.cat((visual, geometry), dim=1)
        raw = self.head(features)
        xy = center_xy + 0.15 * torch.tanh(raw[:, :2])
        return torch.cat((xy, raw[:, 2:4], self.shape_head(features)), dim=1)

def train_reference(out_dir: str, epochs: int = 54,
                    frames_per_seed: int = 300, episode_frames: int = 100,
                    data_dir: str | None = None, seed: int = 0) -> dict:
    """Full reference training run (dataset generation + capped fit + save).

    Training length is epoch-controlled; the Harbor agent phase supplies the
    overall wall-clock limit.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    data_dir = data_dir or str(out / "dataset")
    if not (Path(data_dir) / "meta.json").exists():
        train_harness.generate_dataset(
            data_dir, seeds=spec.DESIGN_SEEDS,
            frames_per_seed=frames_per_seed, episode_frames=episode_frames)
    torch.manual_seed(seed)
    model = PoseNet()
    report = train_harness.fit(
        model, data_dir, epochs=epochs, batch_size=32, lr=1e-3,
        seed=seed, report_path=str(out / "training_report.json"),
        shape_labeler=label_shape)
    torch_contract.save_model(model, str(out / torch_contract.MODEL_FILENAME))
    return report


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--epochs", type=int, default=54)
    ap.add_argument("--frames-per-seed", type=int, default=300)
    ap.add_argument("--episode-frames", type=int, default=100)
    ap.add_argument("--data-dir", default=None)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    report = train_reference(args.out, epochs=args.epochs,
                             frames_per_seed=args.frames_per_seed,
                             episode_frames=args.episode_frames,
                             data_dir=args.data_dir, seed=args.seed)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
