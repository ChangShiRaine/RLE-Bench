"""Calibration for task07 — rewrites the harness config.py.

Runs the reference pickers over the hidden evaluation seeds and pins the
one physics threshold that is meaningless without data: DAMAGE_FORCE_N is
set 30% above the largest 2-tick-sustained contact force either reference
picker exerts during ordinary handling, so the references log ZERO damage
events while genuinely violent strategies (sweeping, slamming) still trip
it. Reference rewards are recorded for the regression tests.

Usage: make calibrate-task07   (python -m dev.calibrate)
"""
from __future__ import annotations

import json
import math
import os
import tempfile

from harness import golden, runtime, scene, spec

CONFIG_PATH = os.path.join(os.path.dirname(__file__), "..", "harness", "config.py")
SEEDS_PATH = os.path.join(os.path.dirname(__file__), "..", "harness", "eval_seeds.json")

PERFECT_BONUS = 0.30
W_SPEED_PERFECT = 0.15
TP_BONUS_CAP_PPM = 15.0
W_CLEAR = 0.35
CLEAR_KNEE, CLEAR_BASE, CLEAR_P = 0.6, 0.10, 3
W_SPEED = 0.20
TP_CAP_PPM = 10.0
W_FLOOR, W_DAMAGE = 0.03, 0.05
W_BIN_HIT = 0.05
BIN_HIT_TICKS, BIN_HIT_REARM_TICKS = 2, 5
GATE_CAP = 0.10
SMOKE_T = 20.0
DMG_TICKS = 2

TEMPLATE = '''"""Calibrated scoring thresholds for task07 (verifier-only).

GENERATED by dev.calibrate — do not hand-edit. NO SEEDS
LIVE HERE — evaluation seeds are in eval_seeds.json (sandbox threat model).

Reward formula:
    perfect = all parts cleared AND zero floor drops   (per episode)
    g(f)    = CLEAR_BASE*(f/CLEAR_KNEE)                      f <= CLEAR_KNEE
            = CLEAR_BASE + (1-CLEAR_BASE)*((f-KNEE)/(1-KNEE))**CLEAR_P
    tp      = 60*cleared / (makespan if bin emptied else budget)  [parts/min]
    score   = PERFECT_BONUS*perfect + W_CLEAR*g(f)
            + W_SPEED*min(tp/TP_CAP_PPM, 1)
            + W_SPEED_PERFECT*perfect*min(tp/TP_BONUS_CAP_PPM, 1)
            - W_FLOOR*floor_drops - W_DAMAGE*damage_events,  clamped [0,1]
Aggregated as the mean over evaluation episodes; a failed gate caps the
total at GATE_CAP.

Calibration run summary:
{summary}"""

GATE_CAP = {gate_cap}

# Perfection: emptying the bin without a single floor drop.
PERFECT_BONUS = {perfect_bonus}      # flat, per episode
W_SPEED_PERFECT = {w_speed_perfect}    # x min(tp/TP_BONUS_CAP_PPM, 1), perfect only
TP_BONUS_CAP_PPM = {tp_bonus_cap}   # pace for the full perfect-speed bonus

# Clearance: progressive curve — the easy first CLEAR_KNEE of the bin earns
# only CLEAR_BASE of the credit; the hard tail rises as a cubic.
W_CLEAR = {w_clear}
CLEAR_KNEE = {clear_knee}
CLEAR_BASE = {clear_base}
CLEAR_P = {clear_p}

# Ordinary speed: capped at a reference pace.
W_SPEED = {w_speed}
TP_CAP_PPM = {tp_cap}

W_FLOOR = {w_floor}          # per part that ever hits the workcell floor
W_DAMAGE = {w_damage}         # per sustained over-force event (per part)
W_BIN_HIT = {w_bin_hit}        # per tool-strike event on the bin

# Tool-bin contact above this, sustained BIN_HIT_TICKS consecutive control
# ticks, is a strike; the force must drop for BIN_HIT_REARM_TICKS before
# another can be counted. Pinned {margin}x above the max sustained tool-bin
# force the reference pickers exert.
BIN_HIT_FORCE_N = {bin_hit_force}
BIN_HIT_TICKS = {bin_hit_ticks}
BIN_HIT_REARM_TICKS = {bin_hit_rearm}

# Sustained (>= DMG_TICKS consecutive control ticks) contact force on a part
# above this counts as damage. Pinned {margin}x above the max sustained force
# either reference picker exerts during ordinary magnet handling.
DAMAGE_FORCE_N = {damage_force}
DMG_TICKS = {dmg_ticks}

# Smoke-probe simulated duration. Determinism uses exact digest equality.
SMOKE_T = {smoke_t}

# Reference anchor scores on the evaluation seeds (regression guards).
GOLDEN_REF_SCORE = {golden_ref}
BASELINE_REF_SCORE = {baseline_ref}
'''


def _episode_score(m):
    from harness.scorer import episode_score
    return episode_score(m)


def main() -> None:
    with open(SEEDS_PATH) as f:
        seeds = json.load(f)
    eval_seeds = list(seeds["eval"])

    print("== golden picker over evaluation seeds ==")
    golden_ms, sustained, tool_bin = [], 0.0, 0.0
    for s in eval_seeds:
        log = runtime.run_episode(golden.GoldenPicker(), s,
                                  budget_t=spec.EPISODE_T, render=False)
        m = log.metrics()
        sustained = max(sustained, log.peak_sustained)
        tool_bin = max(tool_bin, log.peak_tool_bin)
        golden_ms.append(m)
        print(f"  seed {s}: {m['parts_cleared']}/{m['n_parts']} "
              f"floor={m['floor_drops']} sustained={log.peak_sustained:.0f}N "
              f"tool-bin={log.peak_tool_bin:.0f}N")

    print("== baseline picker (public interface) over evaluation seeds ==")
    from harness import baseline
    cell = spec.cell_spec()
    with tempfile.TemporaryDirectory() as td:
        mjb = os.path.join(td, "cell.mjb")
        scene.save_cell_mjb(mjb)
        cell["model_file"] = mjb
        baseline_ms = []
        for s in eval_seeds[:2]:      # rendering makes these ~4 min each
            log = runtime.run_episode(baseline.make_policy(), s,
                                      budget_t=spec.EPISODE_T, render=True,
                                      cell_spec=cell)
            m = log.metrics()
            sustained = max(sustained, log.peak_sustained)
            tool_bin = max(tool_bin, log.peak_tool_bin)
            baseline_ms.append(m)
            print(f"  seed {s}: {m['parts_cleared']}/{m['n_parts']} "
                  f"floor={m['floor_drops']} "
                  f"sustained={log.peak_sustained:.0f}N "
                  f"tool-bin={log.peak_tool_bin:.0f}N")

    damage_force = float(math.ceil(1.3 * sustained / 50.0) * 50)
    bin_hit_force = float(max(math.ceil(1.3 * tool_bin / 50.0) * 50, 100))
    golden_ref = round(sum(_episode_score(m) for m in golden_ms)
                       / len(golden_ms), 4)
    baseline_ref = round(sum(_episode_score(m) for m in baseline_ms)
                         / len(baseline_ms), 4)

    lines = ["golden:   " + " ".join(
        f"{m['parts_cleared']}/{m['n_parts']}" for m in golden_ms)]
    lines.append("baseline: " + " ".join(
        f"{m['parts_cleared']}/{m['n_parts']}" for m in baseline_ms)
        + "  (first 2 eval seeds)")
    lines.append(f"max sustained reference force: {sustained:.0f} N")
    lines.append(f"max sustained reference tool-bin force: {tool_bin:.0f} N")

    with open(CONFIG_PATH, "w") as f:
        f.write(TEMPLATE.format(
            summary="\n".join("    " + ln for ln in lines),
            gate_cap=GATE_CAP, perfect_bonus=PERFECT_BONUS,
            w_speed_perfect=W_SPEED_PERFECT, tp_bonus_cap=TP_BONUS_CAP_PPM,
            w_clear=W_CLEAR, clear_knee=CLEAR_KNEE, clear_base=CLEAR_BASE,
            clear_p=CLEAR_P, w_speed=W_SPEED, tp_cap=TP_CAP_PPM,
            w_floor=W_FLOOR, w_damage=W_DAMAGE, margin=1.3,
            w_bin_hit=W_BIN_HIT, bin_hit_force=bin_hit_force,
            bin_hit_ticks=BIN_HIT_TICKS, bin_hit_rearm=BIN_HIT_REARM_TICKS,
            damage_force=damage_force, dmg_ticks=DMG_TICKS,
            smoke_t=SMOKE_T, golden_ref=golden_ref,
            baseline_ref=baseline_ref))
    print(f"\nwrote {CONFIG_PATH}")
    print(f"  DAMAGE_FORCE_N = {damage_force}")
    print(f"  GOLDEN_REF_SCORE = {golden_ref}")
    print(f"  BASELINE_REF_SCORE = {baseline_ref}")


if __name__ == "__main__":
    main()
